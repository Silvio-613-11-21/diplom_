export interface Restricts {
    lab?: number;
    cmd: string[];
    rl: string[];
    /**
     * Разрешена ли работа с памятью (byte[] / word[]) - Л/Р 3
     */
    memory?: boolean;
    /**
     * Регистры, которые разрешено использовать внутри адресного выражения памяти
     * (например, только SI или только BX + SI)
     */
    indexRegs?: string[];
    /**
     * Регистры, которые запрещены условием задачи (например, BX и SI в задаче 3.0)
     */
    forbiddenRegs?: string[];
    /**
     * Текст задания, который выводится в блоке ограничений
     */
    task?: string;
}
