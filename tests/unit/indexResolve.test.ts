import { describe, it, expect } from 'vitest';
import { idxResv } from 'src/features/parser/model/BTHelpers/IndexResolve';

/**
 * Юнит-тесты разбора адресного выражения (IndexResolve).
 *
 * Функция idxResv принимает содержимое квадратных скобок из byte[...] / word[...]
 * и приводит его к каноническому виду, который потом понимает эмулятор:
 *   регистры ставятся в порядке "база+индекс",
 *   числовое смещение всегда выводится в 16-ричном виде с суффиксом h,
 *   недопустимые сочетания отклоняются (возвращается false).
 */

describe('idxResv - прямые адреса', () => {
    it('возвращает шестнадцатеричное число с суффиксом h', () => {
        expect(idxResv('10h')).toBe('0010');
    });

    it('переводит десятичное число в шестнадцатеричное', () => {
        expect(idxResv('16')).toBe('0010');
    });

    it('переводит двоичное число в шестнадцатеричное', () => {
        expect(idxResv('1010b')).toBe('000a');
    });

    it('разбирает ноль', () => {
        expect(idxResv('0')).toBe('0000');
    });
});

describe('idxResv - косвенная адресация', () => {
    it('оставляет одиночный регистр как есть', () => {
        expect(idxResv('si')).toBe('si');
        expect(idxResv('bx')).toBe('bx');
        expect(idxResv('di')).toBe('di');
    });

    it('ставит базу перед индексом', () => {
        expect(idxResv('si+bx')).toBe('bx+si');
        expect(idxResv('di+bx')).toBe('bx+di');
    });

    it('добавляет смещение к регистру', () => {
        expect(idxResv('si+2')).toBe('si+0002h');
    });

    it('складывает базу, индекс и смещение', () => {
        expect(idxResv('bx+si+4')).toBe('bx+si+0004h');
    });

    it('понимает полурегистры как базу', () => {
        // в задачах Л/Р 3 адрес удобно считать в BH/BL
        expect(idxResv('bh+2')).toBe('bh+0002h');
        expect(idxResv('bl+2')).toBe('bl+0002h');
    });

    it('складывает несколько числовых слагаемых', () => {
        expect(idxResv('10h+5')).toBe('0015');
    });
});

describe('idxResv - отрицательные смещения', () => {
    it('переводит отрицательное смещение в 16-битное представление', () => {
        // -2 в 16-битной арифметике = FFFEh, при вычислении адреса это учтётся
        // (регресс: раньше знак терялся и получалось si+0002h)
        expect(idxResv('si-2')).toBe('si+fffeh');
        expect(idxResv('si-1')).toBe('si+ffffh');
    });

    it('разбирает отрицательное число без регистра', () => {
        // регресс: раньше одиночный минус терялся и получалось 0002
        expect(idxResv('-2')).toBe('fffe');
        expect(idxResv('-1')).toBe('ffff');
    });

    it('вычитание даёт то же, что и отрицательное число', () => {
        expect(idxResv('0-2')).toBe('fffe');
        expect(idxResv('0-2')).toBe(idxResv('-2'));
    });
});

describe('idxResv - недопустимые выражения', () => {
    it('отклоняет два базовых регистра', () => {
        expect(idxResv('bx+bp')).toBe(false);
    });

    it('отклоняет два индексных регистра', () => {
        expect(idxResv('si+di')).toBe(false);
    });

    it('допускает несколько регистров, если это база и индекс', () => {
        expect(idxResv('bx+si')).toBe('bx+si');
    });

    it('отклоняет три регистра', () => {
        expect(idxResv('bx+si+di')).toBe(false);
    });

    it('отклоняет умножение регистра', () => {
        expect(idxResv('si*2')).toBe(false);
    });

    it('отклоняет деление на ноль', () => {
        expect(idxResv('10/0')).toBe(false);
    });

    it('отклоняет мусор вместо числа', () => {
        expect(idxResv('@@')).toBe(false);
    });

    it('отклоняет пустое выражение', () => {
        expect(idxResv('')).toBe(false);
    });
});

describe('idxResv - вычисление арифметики', () => {
    it('выполняет умножение перед сложением', () => {
        expect(idxResv('2*3+1')).toBe('0007');
    });

    it('выполняет вычитание', () => {
        expect(idxResv('10h-1')).toBe('000f');
    });

    it('выполняет деление нацело', () => {
        expect(idxResv('10/3')).toBe('0003');
    });

    it('разбирает смешанные системы счисления', () => {
        // 10h + 1 + 10b = 16 + 1 + 2 = 19 = 13h
        expect(idxResv('10h+1+10b')).toBe('0013');
    });
});
